import { writeFileSync } from 'node:fs'
import { getAddress } from 'viem'
import type { Address } from '@mamoru/domain'
import { address, monadRegistry, type Registry } from '@mamoru/registry'
import { createProxyCall, webAuthnSigner } from '../safe/index.ts'
import { monadV6Deployed, remoteSafe, type RemoteSafeInput } from './index.ts'

/** DeployV3.s.sol `expected(143)`: MamoruActionPolicyV3's pinned address on Monad. */
export const V3_MONAD_PINNED: Address = getAddress('0xd660610193851b0EF85bB526eea35A942cc4F934')

export const FIXTURE_PATH = new URL('../../../contracts/action-policy/test/fixtures/remote-safe-monad.json', import.meta.url)

/** The Monad registry with V3 at its pinned address (until monad.json pins it after the deploy). */
export function withPinnedV3(registry: Registry = monadRegistry): Registry {
  if (registry.entries.some((e) => e.name === 'MamoruActionPolicyV3')) return registry
  return { ...registry, entries: [...registry.entries, { name: 'MamoruActionPolicyV3', kind: 'smart-sessions-policy', role: 'fixture', address: V3_MONAD_PINNED, codeHash: `0x${'00'.repeat(32)}` } as never] }
}

export function fixtureInput(): RemoteSafeInput {
  const backup: Address = '0x000000000000000000000000000000000000bacc'
  return {
    owners: [address('SafeWebAuthnSharedSigner', monadRegistry), backup],
    saltNonce: 46809589425428679530331588158637142457078508681393392316145456181889366683276n,
    webauthn: webAuthnSigner(0x1b2c3d4e5f60718293a4b5c6d7e8f90112233445566778899aabbccddeeff00n, 0x0a1b2c3d4e5f60718293a4b5c6d7e8f90112233445566778899aabbccddeeffn, monadRegistry),
    policy: monadV6Deployed(withPinnedV3()),
    sessionKey: '0x00000000000000000000000000000000005e5510',
    validAfter: 1_790_000_000,
    validUntil: 1_821_536_000,
    capUsdc: 1_500_000_000n,
  }
}

export function fixture() {
  const input = fixtureInput()
  const r = remoteSafe(input)
  const call = createProxyCall(r.setup, monadRegistry)
  return {
    note: 'Generated by packages/account/remote/fixture.ts (otto/mamoru#251). Do not edit.',
    factory: call.to,
    createProxy: call.data,
    expected: r.address,
    owners: input.owners,
    actionPolicy: V3_MONAD_PINNED,
    gasPolicy: address('MamoruGasPolicy', monadRegistry),
    permissionIds: r.permissionIds,
  }
}

export function fixtureJson(): string {
  return `${JSON.stringify(fixture(), null, 2)}\n`
}

if (import.meta.main && process.argv.includes('--write')) writeFileSync(FIXTURE_PATH, fixtureJson())
