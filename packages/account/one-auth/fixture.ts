// V4RemoteInitParity.t.sol rebuilds with MamoruV4Helper.remote (no fork) and compares byte for byte. one-auth.test.ts fails
// while the committed file differs from what this builds. Regenerate: bun packages/account/one-auth/fixture.ts --write
import { writeFileSync } from 'node:fs'
import { getContractAddress, zeroAddress } from 'viem'
import type { Address } from '@mamoru/domain'
import { address, baseRegistry, monadRegistry } from '@mamoru/registry'
import { encodeInitV4 } from '@mamoru/policy'
import { webAuthnSigner } from '../safe/index.ts'
import { ownerStateOf, v4Children, v4HomeSession, v4OwnersHash, v4Remote } from './index.ts'

/** Test-only deployers: V4 and MamoruGasPolicyV2 are created by these EOAs at these nonces (CREATE: bytecode-independent). */
export const FIXTURE_V4_DEPLOYER: Address = '0x00000000000000000000000000000000000Da4D4'
export const FIXTURE_V4_NONCE = 7n
export const FIXTURE_GAS_DEPLOYER: Address = '0x00000000000000000000000000000000000Ba5D2'
export const FIXTURE_GAS_NONCE = 3n
export const FIXTURE_GUARDIAN: Address = '0x000000000000000000000000000000000000Ce11'
export const FIXTURE_REGISTRY: Address = '0x000000000000000000000000000000000000Fe91'
export const FIXTURE_HOME: Address = '0x0000000000000000000000000000000000A11CE0'
export const FIXTURE_SESSION_KEY: Address = '0x00000000000000000000000000000000005e55e5'

export const FIXTURE_PATH = new URL('../../../contracts/action-policy/test/fixtures/v4-remote-init.json', import.meta.url)

export function fixture() {
  const policy = getContractAddress({ from: FIXTURE_V4_DEPLOYER, nonce: FIXTURE_V4_NONCE })
  const gasPolicy = getContractAddress({ from: FIXTURE_GAS_DEPLOYER, nonce: FIXTURE_GAS_NONCE })
  const deployment = { policy, gasPolicy }
  const backup: Address = '0x000000000000000000000000000000000000bacc'
  const owners = [address('SafeWebAuthnSharedSigner', baseRegistry), backup]
  const passkey = webAuthnSigner(0x1b2c3d4e5f60718293a4b5c6d7e8f90112233445566778899aabbccddeeff00n, 0x0a1b2c3d4e5f60718293a4b5c6d7e8f90112233445566778899aabbccddeeffn, baseRegistry)
  const o = ownerStateOf(owners, passkey, baseRegistry)
  const capUsd = 10_000_000_000n
  const r = v4Remote({ home: FIXTURE_HOME, owners: o, domain: 15, homeDomain: 6, sessionKey: FIXTURE_SESSION_KEY, capUsd, deployment, registry: monadRegistry })
  // A remote of an account with no passkey owner: MamoruRemoteInit is delegatecalled directly (no MultiSend).
  const plain = ownerStateOf([backup], null, baseRegistry)
  const rPlain = v4Remote({ home: FIXTURE_HOME, owners: plain, domain: 6, homeDomain: 15, sessionKey: FIXTURE_SESSION_KEY, capUsd: 5_000_000n, deployment, registry: baseRegistry })
  const admit = [12345n, (1n << 255n) | 777n]
  const home = v4HomeSession({ sessionKey: FIXTURE_SESSION_KEY, deployment, capUsd, generation: 1n, admit, registry: baseRegistry })
  const children = v4Children(policy)
  return {
    note: 'Generated by packages/account/one-auth/fixture.ts (otto/mamoru#293). Do not edit.',
    v4Deployer: FIXTURE_V4_DEPLOYER,
    v4Nonce: Number(FIXTURE_V4_NONCE),
    gasDeployer: FIXTURE_GAS_DEPLOYER,
    gasNonce: Number(FIXTURE_GAS_NONCE),
    guardian: FIXTURE_GUARDIAN,
    registry: FIXTURE_REGISTRY,
    policy,
    gasPolicy,
    remoteInit: children.remoteInit,
    helper: children.helper,
    home: FIXTURE_HOME,
    owners,
    threshold: 1,
    x: `0x${o.x.toString(16).padStart(64, '0')}`,
    y: `0x${o.y.toString(16).padStart(64, '0')}`,
    verifiers: `0x${o.verifiers.toString(16).padStart(64, '0')}`,
    sessionKey: FIXTURE_SESSION_KEY,
    capUsd: Number(capUsd),
    ownersHash: v4OwnersHash(o),
    monad: { domain: 15, homeDomain: 6, expected: r.address, createCall: r.createCall.data, sessions: r.sessions, permissionId: r.permissionId },
    plain: { owner: backup, domain: 6, homeDomain: 15, capUsd: 5_000_000, expected: rPlain.address, createCall: rPlain.createCall.data, ownersHash: v4OwnersHash(plain) },
    homeSession: { admit: admit.map((a) => `0x${a.toString(16).padStart(64, '0')}`), init: encodeInitV4({ capUsd, generation: 1n, home: zeroAddress, homeDomain: 0, admit }), gasInit: home.userOpPolicies[0]!.initData, salt: home.salt },
  }
}

export function fixtureJson(): string {
  return `${JSON.stringify(fixture(), null, 2)}\n`
}

if (import.meta.main && process.argv.includes('--write')) writeFileSync(FIXTURE_PATH, fixtureJson())
